"""Repository interface. The engine only talks to this; PostGIS details live in the implementation."""
from datetime import datetime
from typing import Dict, List, Optional, Protocol, Sequence
from uuid import UUID

from .domain import Candidate, ComplaintRecord, NewReport, ReportRecord


class ComplaintRepository(Protocol):
    def find_candidates(self, issue_type: str, latitude: float, longitude: float, radius_m: float,
                        created_after: datetime, statuses: Sequence[str],
                        exclude_complaint_id: Optional[UUID] = None) -> List[Candidate]: ...
    def get_embeddings(self, complaint_ids: Sequence[UUID]) -> Dict[UUID, List[List[float]]]: ...
    def get_complaint(self, complaint_id: UUID) -> Optional[ComplaintRecord]: ...
    def get_reports(self, complaint_id: UUID) -> List[ReportRecord]: ...
    def insert_complaint(self, complaint_id: UUID, issue_type: str, status: str, latitude: float,
                         longitude: float, department_id: Optional[UUID], created_at: datetime) -> None: ...
    def upsert_report(self, report: NewReport) -> UUID: ...
    def move_reports(self, report_ids: Sequence[UUID], to_complaint_id: UUID) -> None: ...
    def refresh_report_count(self, complaint_id: UUID) -> int: ...
    def update_complaint_priority(self, complaint_id: UUID, score: float, band: str, reason: str,
                                  updated_at: datetime) -> None: ...
    def get_department_id(self, name: str) -> Optional[UUID]: ...
    def add_status_history(self, complaint_id: UUID, officer_id: Optional[UUID], old_status: str,
                           new_status: str, comment: str, created_at: datetime) -> None: ...
    def list_open_complaint_ids(self, statuses: Sequence[str]) -> List[UUID]: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
